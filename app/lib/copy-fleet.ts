// Words for the fleet: the types and airlines flown, and the aircraft on a flight.

const hans = {
  // A no-break space keeps each count on the line with its measure word.
  hero: (types: string, carriers: string) => `坐过 ${types}\u00a0种机型、${carriers}\u00a0家航空公司`,
  yearHero: (year: number, types: string, carriers: string) => `${year} 年坐了 ${types}\u00a0种机型、${carriers}\u00a0家航空公司`,
  none: "还没有记下机型",
  types: "机型",
  carriers: "航空公司",
  scale: "按真实尺寸排列",
  moreTails: (count: string) => `显示全部 ${count} 架`,
  lead: (first: string, last: string, count: string) => `第一次是 ${first}，最近一次是 ${last}。一共 ${count} 次。`,
  once: (date: string) => `${date}坐过一次。`,
  typical: (count: string, total: string) => count === total ? "机型都是按航线的常用机型推断的。" : `其中 ${count} 次是按航线的常用机型推断的。`,
  span: "翼展",
  height: "高度",
  firstFlight: "首飞",
  metres: (value: string) => `${value} 米`,
  year: (value: string) => `${value} 年`,
  tails: "坐过的飞机",
  tailCount: (count: string) => `${count} 次`,
  routes: "航线",
  all: (count: string) => `查看这 ${count} 次航班`,
  typeNotFound: "档案里没有这个机型",
  carrierNotFound: "档案里没有这家航空公司",
  // Labels under a figure; English needs the count to pick singular or plural.
  flights: ((() => "次航班") as (count: string) => string),
  km: "公里",
  hours: "小时",
  routeCount: ((() => "条航线") as (count: string) => string),
  credit: (name: string) => name ? `摄影 ${name} · Planespotters` : "Planespotters",
  onType: (count: string) => `坐过这个机型 ${count} 次`,
  mostType: (name: string, count: string) => `坐得最多的机型是 ${name}，${count} 次`,
  typeRest: (names: string[]) => `其次是 ${names.join("、")}`,
};

